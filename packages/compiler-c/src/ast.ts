import type {SourceSpan} from "./lexer.js";
export type CType="int"|"void";
export type Program={kind:"Program";functions:FunctionDefinition[];span:SourceSpan};
export type FunctionDefinition={kind:"FunctionDefinition";name:string;returnType:CType;parameters:Parameter[];body:BlockStatement;span:SourceSpan};
export type Parameter={kind:"Parameter";name:string;type:CType;span:SourceSpan};
export type Statement=BlockStatement|VariableDeclaration|ReturnStatement|IfStatement|WhileStatement|ExpressionStatement;
export type BlockStatement={kind:"BlockStatement";statements:Statement[];span:SourceSpan};
export type VariableDeclaration={kind:"VariableDeclaration";name:string;type:CType;initializer:Expression|null;span:SourceSpan};
export type ReturnStatement={kind:"ReturnStatement";expression:Expression|null;span:SourceSpan};
export type IfStatement={kind:"IfStatement";condition:Expression;thenBranch:Statement;elseBranch:Statement|null;span:SourceSpan};
export type WhileStatement={kind:"WhileStatement";condition:Expression;body:Statement;span:SourceSpan};
export type ExpressionStatement={kind:"ExpressionStatement";expression:Expression|null;span:SourceSpan};
export type Expression=IntegerLiteral|IdentifierExpression|UnaryExpression|BinaryExpression|AssignmentExpression|CallExpression;
export type IntegerLiteral={kind:"IntegerLiteral";value:number;span:SourceSpan};
export type IdentifierExpression={kind:"IdentifierExpression";name:string;span:SourceSpan};
export type UnaryExpression={kind:"UnaryExpression";operator:"+"|"-"|"!";operand:Expression;span:SourceSpan};
export type BinaryExpression={kind:"BinaryExpression";operator:"+"|"-"|"*"|"/"|"%"|"=="|"!="|"<"|"<="|">"|">="|"&&"|"||";left:Expression;right:Expression;span:SourceSpan};
export type AssignmentExpression={kind:"AssignmentExpression";target:IdentifierExpression;value:Expression;span:SourceSpan};
export type CallExpression={kind:"CallExpression";callee:string;arguments:Expression[];span:SourceSpan};
